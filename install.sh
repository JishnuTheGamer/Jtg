    local TARGET=$1
    local PANEL_NAME="Main Panel"
    local PORT="6767"
    local SERVICE_NAME="jtg-main"
    
    if [ "$TARGET" = "dev" ]; then
        PANEL_NAME="Developer Panel"
        PORT="3000"
        SERVICE_NAME="jtg-admin"
    fi

    print_banner
    echo -e "╔══════════════════════════════════════════════╗"
    echo -e "║          SELECT INSTALLATION MODE            ║"
    echo -e "╠══════════════════════════════════════════════╣"
    echo -e "║                                              ║"
    echo -e "║  1) Node.js with PM2 (Recommended)          ║"
    echo -e "║     • Panel runs on Node.js via PM2          ║"
    echo -e "║     • Docker used for Minecraft servers      ║"
    echo -e "║  2) Docker Container (All in Docker)         ║"
    echo -e "║  3) Back                                     ║"
    echo -e "║                                              ║"
    echo -e "╚══════════════════════════════════════════════╝"
    
    local MODE_CHOICE=""
    if [ -n "$RUN_CHOICE" ]; then
        MODE_CHOICE="$RUN_CHOICE"
    elif [ ! -t 0 ]; then
        MODE_CHOICE="1"
    else
        read -p " Choose an option (1-3): " MODE_CHOICE
    fi

    if [ "$MODE_CHOICE" = "3" ]; then
        return
    fi

    if [ "$MODE_CHOICE" != "1" ] && [ "$MODE_CHOICE" != "2" ]; then
        log_error "Invalid selection."
        sleep 1
        return
    fi
    
    if [ "$TARGET" = "main" ]; then
        print_banner
        echo -e "╔══════════════════════════════════════════════╗"
        echo -e "║              CREATE OWNER ACCOUNT            ║"
        echo -e "╠══════════════════════════════════════════════╣"
        
        local OWNER_USER=""
        local OWNER_PASS=""
        local OWNER_PASS2=""
        
        if [ -n "$JTG_OWNER_USER" ] && [ -n "$JTG_OWNER_PASS" ]; then
            OWNER_USER="$JTG_OWNER_USER"
            OWNER_PASS="$JTG_OWNER_PASS"
        elif [ ! -t 0 ]; then
            OWNER_USER="owner"
            OWNER_PASS="owner12345"
        else
            while true; do
                read -p "║ Username: " OWNER_USER
                if [ ${#OWNER_USER} -ge 3 ]; then
                    break
                else
                    echo "║ Username must be at least 3 characters. Try again."
                fi
            done
            
            while true; do
                read -s -p "║ Password: " OWNER_PASS
                echo ""
                read -s -p "║ Confirm Password: " OWNER_PASS2
                echo ""
                if [ ${#OWNER_PASS} -lt 6 ]; then
                    echo "║ Password must be at least 6 characters. Try again."
                elif [ "$OWNER_PASS" = "$OWNER_PASS2" ] && [ -n "$OWNER_PASS" ]; then
                    break
                else
                    echo "║ Passwords do not match or are empty. Try again."
                fi
            done
        fi
        echo -e "╚══════════════════════════════════════════════╝"
        
        export JTG_OWNER_USER="$OWNER_USER"
        export JTG_OWNER_PASS="$OWNER_PASS"
    fi
    
    # Environment Setup
    mkdir -p .data backups
    if [ ! -f ".env" ]; then
        if [ -f ".env.example" ]; then
            cp .env.example .env
        else
            echo "PORT=6767" > .env
            echo "JWT_SECRET=$(head -c 32 /dev/urandom | base64 2>/dev/null || openssl rand -base64 32)" >> .env
        fi
    fi

    print_banner
    echo -e "╔══════════════════════════════════════════════╗"
    echo -e "║              INSTALLATION PROGRESS           ║"
    echo -e "╚══════════════════════════════════════════════╝
"

    execute_step "System Requirement Check" check_system_deps
    
    if [ "$MODE_CHOICE" = "1" ]; then
        execute_step "Node.js Configuration" setup_node_env
        execute_step "NPM Dependencies" install_dependencies
        if [ "$TARGET" = "main" ]; then
            execute_step "Owner Account Setup" setup_owner
            execute_step "Building Application" build_application
            execute_step "Starting PM2 Service" start_panel_node jtg-main
            execute_step "Waiting for Application & Port 6767" health_check 6767 pm2 jtg-main
        else
            execute_step "Building Application" build_application
            execute_step "Starting PM2 Service" start_panel_node jtg-admin
            execute_step "Waiting for Application & Port 3000" health_check 3000 pm2 jtg-admin
        fi
    else
        execute_step "Docker Configuration" setup_docker_env
        if [ "$TARGET" = "main" ]; then
            execute_step "Building & Starting Docker Container" start_panel_docker jtg-main
            execute_step "Owner Account Setup" setup_owner_docker jtg-main
            execute_step "Waiting for Application & Port 6767" health_check 6767 docker jtg-main
        else
            execute_step "Building & Starting Docker Container" start_panel_docker jtg-admin
            execute_step "Waiting for Application & Port 3000" health_check 3000 docker jtg-admin
        fi
    fi
    
    show_status

    local IP=$(curl -s -m 2 ifconfig.me 2>/dev/null || curl -s -m 2 icanhazip.com 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}' || echo "localhost")
    if [ "$TARGET" = "main" ]; then
        log_success "JTG Main Panel installation is complete and verified!"
        echo -e "${GREEN}✓ You can now open http://${IP}:6767 and log in with '${OWNER_USER}'.${NC}
"
    else
        log_success "JTG Developer Panel installation is complete and verified!"
        echo -e "${GREEN}✓ Developer Panel running on http://${IP}:3000.${NC}
"
    fi
}

update_panel() {
    if [ ! -f "update.sh" ]; then
        log_error "update.sh not found."
        return
    fi
    bash update.sh
}

create_owner_user() {
    print_banner
    echo -e "╔══════════════════════════════════════════════╗"
    echo "║              CREATE OWNER ACCOUNT            ║"
    echo "╚══════════════════════════════════════════════╝"
    
    local OWNER_USER=""
    local OWNER_PASS=""
    local OWNER_PASS2=""
    
    while true; do
        read -p "  Username: " OWNER_USER
        if [ ${#OWNER_USER} -ge 3 ]; then
            break
        else
            echo "  Username must be at least 3 characters. Try again."
        fi
    done
    
    while true; do
        read -s -p "  Password: " OWNER_PASS
        echo ""
        read -s -p "  Confirm Password: " OWNER_PASS2
        echo ""
        if [ ${#OWNER_PASS} -lt 6 ]; then
            echo "  Password must be at least 6 characters. Try again."
        elif [ "$OWNER_PASS" = "$OWNER_PASS2" ] && [ -n "$OWNER_PASS" ]; then
            break
        else
