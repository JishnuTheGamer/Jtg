EOF2
    fi
}

install_dependencies() {
    if [ -f "package-lock.json" ]; then
        npm ci || npm install
    else
        npm install
    fi
}

setup_owner() {
    npm run createuser
}

build_application() {
    npm run build
}

start_panel_docker() {
    local TARGET=$1
    if command -v docker-compose &> /dev/null; then
        docker-compose up -d --build "$TARGET"
    elif command -v docker &> /dev/null && docker compose version &> /dev/null; then
        docker compose up -d --build "$TARGET"
    else
        echo "Docker Compose not found."
        return 1
    fi
    
    sleep 2
    local container_status=$(docker inspect --format '{{.State.Status}}' "$TARGET" 2>/dev/null || echo "not_found")
    if [ "$container_status" == "exited" ] || [ "$container_status" == "dead" ] || [ "$container_status" == "not_found" ]; then
        echo "Docker container $TARGET failed to start. Status: $container_status"
        echo "--- Docker Logs for $TARGET ---"
        docker logs "$TARGET" --tail 40 2>&1 || true
        return 1
    fi
    return 0
}

start_panel_node() {
    local TARGET=$1
    run_pm2 delete "$TARGET" 2>/dev/null || true
    run_pm2 start ecosystem.config.cjs --only "$TARGET"
    run_pm2 save --force 2>/dev/null || true
}

health_check() {
    local PORT=$1
    local RUNTIME_TYPE=$2
    local TARGET=$3
    local ATTEMPTS=0
    local MAX_ATTEMPTS=30

    while [ $ATTEMPTS -lt $MAX_ATTEMPTS ]; do
        if curl -s -f "http://127.0.0.1:${PORT}/api/health" >/dev/null 2>&1 || curl -s -f "http://127.0.0.1:${PORT}/" >/dev/null 2>&1; then
            return 0
        fi
        
        if [ "$RUNTIME_TYPE" == "docker" ]; then
            local cstatus=$(docker inspect --format '{{.State.Status}}' "$TARGET" 2>/dev/null || echo "not_found")
            if [ "$cstatus" == "exited" ] || [ "$cstatus" == "dead" ]; then
                echo "Container $TARGET exited unexpectedly during health check."
                echo "--- Logs for $TARGET ---"
                docker logs "$TARGET" --tail 50 2>&1 || true
                return 1
            fi
        else
            if run_pm2 list 2>/dev/null | grep "$TARGET" | grep -qE "errored|stopped"; then
                echo "PM2 process $TARGET crashed or stopped."
                echo "--- Logs for $TARGET ---"
                run_pm2 logs "$TARGET" --lines 40 --nostream 2>&1 || true
                return 1
            fi
        fi
        
        sleep 2
        ATTEMPTS=$((ATTEMPTS + 1))
    done

    echo "Health check timed out waiting for application on port $PORT."
    if [ "$RUNTIME_TYPE" == "docker" ]; then
        echo "--- Container Status ---"
        docker ps -a --filter "name=$TARGET" || true
        echo "--- Docker Logs ---"
        docker logs "$TARGET" --tail 50 2>&1 || true
    else
        echo "--- PM2 Status ---"
        run_pm2 list || true
        echo "--- PM2 Logs ---"
        run_pm2 logs "$TARGET" --lines 50 --nostream || true
    fi
    return 1
}

check_port() {
    local PORT=$1
    if command -v ss &> /dev/null; then
        if ss -lnt | grep -q ":$PORT "; then return 1; fi
    elif command -v netstat &> /dev/null; then
        if netstat -tuln | grep -q ":$PORT "; then return 1; fi
    elif command -v lsof &> /dev/null; then
        if lsof -i :$PORT -sTCP:LISTEN -t >/dev/null 2>&1; then return 1; fi
    fi
    return 0
}

show_status() {
    local MAIN_STATUS="OFF"
    local DEV_STATUS="OFF"
    local SFTP_STATUS="OFF"
    
    if (run_pm2 list 2>/dev/null | grep "jtg-main" | grep -q "online") || \
       (command -v docker &> /dev/null && docker ps --format '{{.Names}}' 2>/dev/null | grep -q "^jtg-main$") || \
       curl -s -m 2 http://127.0.0.1:6767/api/health 2>/dev/null | grep -q "JTG Panel"; then
        MAIN_STATUS="ONLINE"
    fi
    
    if (run_pm2 list 2>/dev/null | grep "jtg-admin" | grep -q "online") || \
       (command -v docker &> /dev/null && docker ps --format '{{.Names}}' 2>/dev/null | grep -q "^jtg-admin$") || \
       curl -s -m 2 http://127.0.0.1:3000/api/health 2>/dev/null | grep -q "JTG Panel"; then
        DEV_STATUS="ONLINE"
    fi
    
    if [ "$MAIN_STATUS" == "ONLINE" ] || [ "$DEV_STATUS" == "ONLINE" ]; then
        SFTP_STATUS="ONLINE"
    fi
    
    local IP=$(curl -s -m 2 ifconfig.me 2>/dev/null || curl -s -m 2 icanhazip.com 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}' || echo "localhost")

    echo -e "\n${CYAN}${BOLD}╔══════════════════════════════════════════════╗"
    echo -e "║              JTG PANEL STATUS                ║"
    echo -e "╠══════════════════════════════════════════════╣${NC}"
    echo -e "║"
    if [ "$MAIN_STATUS" == "ONLINE" ]; then
        echo -e "║  Main Panel       : ${GREEN}ONLINE${NC} (http://${IP}:6767)"
    else
        echo -e "║  Main Panel       : ${RED}OFF${NC}"
    fi
    echo -e "║  Main Port        : 6767"
    if [ "$DEV_STATUS" == "ONLINE" ]; then
        echo -e "║  Developer Panel  : ${GREEN}ONLINE${NC} (http://${IP}:3000)"
    else
        echo -e "║  Developer Panel  : ${YELLOW}OFF${NC}"
    fi
    echo -e "║  Developer Port   : 3000"
    if [ "$SFTP_STATUS" == "ONLINE" ]; then
        echo -e "║  SFTP Service     : ${GREEN}ONLINE${NC} (Port 2022)"
    else
        echo -e "║  SFTP Service     : ${RED}OFF${NC}"
    fi
    echo -e "║"
    echo -e "${CYAN}${BOLD}╚══════════════════════════════════════════════╝${NC}\n"
}

install_panel() {
    local TARGET=$1
    local PANEL_NAME="Main Panel"
    local PORT="6767"
    local SERVICE_NAME="jtg-main"
    
    if [ "$TARGET" == "dev" ]; then
        PANEL_NAME="Developer Panel"
        PORT="3000"
        SERVICE_NAME="jtg-admin"
    fi

    print_banner
    echo -e "╔══════════════════════════════════════════════╗"
    echo -e "║          SELECT INSTALLATION MODE            ║"
    echo -e "╠══════════════════════════════════════════════╣"
    echo -e "║                                              ║"
    echo -e "║  1) Docker                                   ║"
    echo -e "║  2) Local Node.js                            ║"
    echo -e "║  3) Back                                     ║"
    echo -e "║                                              ║"
    echo -e "╚══════════════════════════════════════════════╝"
    
    local MODE_CHOICE=""
    if [ -n "$RUN_CHOICE" ]; then
        MODE_CHOICE="$RUN_CHOICE"
    else
        read -p " Choose an option (1-3): " MODE_CHOICE
    fi

    if [ "$MODE_CHOICE" == "3" ]; then
        return
    fi

    if [ "$MODE_CHOICE" != "1" ] && [ "$MODE_CHOICE" != "2" ]; then
        log_error "Invalid selection."
        sleep 1
        return
    fi
    
    if [ "$TARGET" == "main" ]; then
        print_banner
        echo -e "╔══════════════════════════════════════════════╗"
        echo -e "║              CREATE OWNER ACCOUNT            ║"
        echo -e "╠══════════════════════════════════════════════╣"
        
        local OWNER_USER=""
        local OWNER_PASS=""
        local OWNER_PASS2=""
        
        if [ -n "$JTG_OWNER_USER" ] && [ -n "$JTG_OWNER_PASS" ]; then
            OWNER_USER="$JTG_OWNER_USER"
            OWNER_PASS="$JTG_OWNER_PASS"
        else
            while true; do
                read -p "║ Username: " OWNER_USER
                if [ -n "$OWNER_USER" ]; then
                    break
                fi
            done
            
            while true; do
                read -s -p "║ Password: " OWNER_PASS
                echo ""
                read -s -p "║ Confirm Password: " OWNER_PASS2
                echo ""
                if [ "$OWNER_PASS" == "$OWNER_PASS2" ] && [ -n "$OWNER_PASS" ]; then
                    break
                else
                    echo "║ Passwords do not match or are empty. Try again."
                fi
            done
        fi
        echo -e "╚══════════════════════════════════════════════╝"
        
        export JTG_OWNER_USER="$OWNER_USER"
        export JTG_OWNER_PASS="$OWNER_PASS"
    fi
    
    # Environment Setup
    mkdir -p .data backups
    if [ ! -f ".env" ]; then
        if [ -f ".env.example" ]; then
            cp .env.example .env
        else
            echo "PORT=6767" > .env
            echo "JWT_SECRET=$(head -c 32 /dev/urandom | base64 2>/dev/null || openssl rand -base64 32)" >> .env
        fi
    fi

    print_banner
    echo -e "╔══════════════════════════════════════════════╗"
    echo -e "║              INSTALLATION PROGRESS           ║"
    echo -e "╚══════════════════════════════════════════════╝\n"

    execute_step "System Requirement Check" check_system_deps
    
    if [ "$MODE_CHOICE" == "1" ]; then
        execute_step "Docker Configuration" setup_docker_env
        execute_step "Node Environment" install_node
        execute_step "NPM Dependencies" install_dependencies
        if [ "$TARGET" == "main" ]; then
            execute_step "Owner Account Setup" setup_owner
            execute_step "Building & Starting Docker Container" start_panel_docker jtg-main
            execute_step "Waiting for Application & Port 6767" health_check 6767 docker jtg-main
        else
            execute_step "Building & Starting Docker Container" start_panel_docker jtg-admin
            execute_step "Waiting for Application & Port 3000" health_check 3000 docker jtg-admin
        fi
    else
        execute_step "Node.js Configuration" setup_node_env
        execute_step "NPM Dependencies" install_dependencies
        if [ "$TARGET" == "main" ]; then
            execute_step "Owner Account Setup" setup_owner
            execute_step "Building Application" build_application
            execute_step "Starting PM2 Service" start_panel_node jtg-main
            execute_step "Waiting for Application & Port 6767" health_check 6767 pm2 jtg-main
        else
            execute_step "Building Application" build_application
            execute_step "Starting PM2 Service" start_panel_node jtg-admin
            execute_step "Waiting for Application & Port 3000" health_check 3000 pm2 jtg-admin
        fi
    fi
    
    show_status

    local IP=$(curl -s -m 2 ifconfig.me 2>/dev/null || curl -s -m 2 icanhazip.com 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}' || echo "localhost")
    if [ "$TARGET" == "main" ]; then
        log_success "JTG Main Panel installation is complete and verified!"
        echo -e "${GREEN}✓ You can now open http://${IP}:6767 and log in with '${OWNER_USER}'.${NC}\n"
    else
        log_success "JTG Developer Panel installation is complete and verified!"
        echo -e "${GREEN}✓ Developer Panel running on http://${IP}:3000.${NC}\n"
    fi
}

update_panel() {
    if [ ! -f "update.sh" ]; then
        log_error "update.sh not found."
        return
    fi
    bash update.sh
}

create_owner_user() {
    print_banner
    echo -e "╔══════════════════════════════════════════════╗"
    echo "║              CREATE OWNER ACCOUNT            ║"
    echo "╚══════════════════════════════════════════════╝"
    
    local OWNER_USER=""
    local OWNER_PASS=""
    local OWNER_PASS2=""
    
    while true; do
        read -p "  Username: " OWNER_USER
        if [ -n "$OWNER_USER" ]; then
            break
        fi
    done
    
    while true; do
        read -s -p "  Password: " OWNER_PASS
        echo ""
        read -s -p "  Confirm Password: " OWNER_PASS2
        echo ""
        if [ "$OWNER_PASS" == "$OWNER_PASS2" ] && [ -n "$OWNER_PASS" ]; then
            break
        else
            echo "  Passwords do not match or are empty. Try again."
        fi
    done
    
    export JTG_OWNER_USER="$OWNER_USER"
    export JTG_OWNER_PASS="$OWNER_PASS"
    execute_step "Setting up Owner Account" setup_owner
    log_success "Owner user setup completed successfully!"
}

uninstall_panel() {
    if [ ! -f "uninstall.sh" ]; then
        log_error "uninstall.sh not found."
        return
    fi
    bash uninstall.sh
}

# Direct invocation support: bash install.sh main / bash install.sh dev
if [ "$1" == "main" ]; then
    install_panel "main"
    exit 0
elif [ "$1" == "dev" ]; then
    install_panel "dev"
    exit 0
fi

while true; do
    print_banner
    echo -e "  ${BOLD}1)${NC} Initialize Main Panel"
    echo -e "  ${BOLD}2)${NC} Initialize Developer Panel"
    echo -e "  ${BOLD}3)${NC} Update JTG Panel"
    echo -e "  ${BOLD}4)${NC} Create Owner"
    echo -e "  ${BOLD}5)${NC} Uninstall JTG Panel"
    echo -e "  ${BOLD}6)${NC} Exit"
    echo -e "\n========================================================"
    if ! read -p " Choose an option (1-6): " CHOICE; then
        echo ""
        break
    fi
    case "$CHOICE" in
        1)
            install_panel "main"
            if [ -t 0 ]; then read -p "Press Enter to return to main menu..." || true; fi
            ;;
        2)
            install_panel "dev"
            if [ -t 0 ]; then read -p "Press Enter to return to main menu..." || true; fi
            ;;
        3)
            update_panel
            if [ -t 0 ]; then read -p "Press Enter to return to main menu..." || true; fi
            ;;
        4)
            create_owner_user
            if [ -t 0 ]; then read -p "Press Enter to return to main menu..." || true; fi
            ;;
        5)
            uninstall_panel
            if [ -t 0 ]; then read -p "Press Enter to return to main menu..." || true; fi
            ;;
        6)
            echo -e "\n${YELLOW}Exiting script... Goodbye!${NC}\n"
            exit 0
            ;;
        *)
            log_error "Invalid option!"
            sleep 1.5
            ;;
    esac
done
